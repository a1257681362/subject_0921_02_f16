-- ============================================================
-- apt-4 公寓交接班线上化 + DFA 敏感词过滤
--
-- 1. 交接班记录由纸面转线上：登记（交班）→ 接班人确认，按小区/楼栋/班次/日期/状态检索。
-- 2. 敏感词走确定有限自动机（DFA/Trie），词典后台维护、即时生效：
--    文本先归一化（去插空分隔符与零宽字符、全角转半角、大小写折叠、形近混淆替换），
--    在归一化串上跑 DFA，命中位置回映原文——分隔符插空也能命中，位置可定位。
-- 3. 分级：BLOCK(2) 命中即拦截（痕迹独立事务留痕，业务整体回滚但痕迹保留）；
--    MASK(1) 命中自动打码后放行；每一次命中均落 t_sensitive_audit，可定位到账号与字段。
-- 4. 词典每一次后台维护落 t_sensitive_word_op_log；命中痕迹与维护留痕默认仅 ALL 范围可见。
-- ============================================================

-- 交接班记录：替代纸质交接本，只增不删，状态机 DRAFT -> CONFIRMED
CREATE TABLE IF NOT EXISTS t_handover_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community VARCHAR(128) NOT NULL,
    building VARCHAR(64) NOT NULL,
    shift VARCHAR(16) NOT NULL,                   -- MORNING / EVENING 早班/晚班
    shift_date DATE NOT NULL,
    handover_by VARCHAR(64) NOT NULL,            -- 交班人（=operator 审计字段）
    take_over_by VARCHAR(64),                    -- 接班人；确认前为空
    pending_items VARCHAR(1024),                 -- 待办事项
    keys_card_count INT,                         -- 钥匙/门卡数量
    cash_amount DECIMAL(12,2),                   -- 备用金/现金交接
    content VARCHAR(2048) NOT NULL,              -- 交接内容（必填）
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT', -- DRAFT 待确认 / CONFIRMED 已确认
    confirmed_at TIMESTAMP,
    confirm_request_no VARCHAR(64),
    request_no VARCHAR(64) NOT NULL,
    operator VARCHAR(64) NOT NULL,
    biz_time TIMESTAMP NOT NULL,
    data_version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_handover_lookup ON t_handover_record (community, building, shift_date);
CREATE INDEX IF NOT EXISTS idx_handover_operator ON t_handover_record (operator);
CREATE INDEX IF NOT EXISTS idx_handover_status ON t_handover_record (status);

-- 敏感词词典：后台维护，改动后引擎整体重建、即时生效
CREATE TABLE IF NOT EXISTS t_sensitive_word (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_text VARCHAR(128) NOT NULL,             -- 明文词条（内部归一化形式存储）
    category VARCHAR(32) NOT NULL DEFAULT 'ILLEGAL', -- AD 广告 / ILLEGAL 违规 / OTHER
    action_level INT NOT NULL DEFAULT 1,         -- 1=MASK 打码放行, 2=BLOCK 拦截
    normalize_hint VARCHAR(255),                 -- 可选：同行动 MASK 时指示打码字符等（保留扩展）
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',   -- ACTIVE / DISABLED
    created_by VARCHAR(64) NOT NULL,
    updated_by VARCHAR(64),
    remark VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_sensitive_word_text UNIQUE (word_text)
);
CREATE INDEX IF NOT EXISTS idx_sensitive_word_status ON t_sensitive_word (status);

-- 敏感词维护操作日志：谁在何时把哪条词改成什么，只增不改
-- action: CREATE / UPDATE / DISABLE / ENABLE
CREATE TABLE IF NOT EXISTS t_sensitive_word_op_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_id BIGINT,
    word_text VARCHAR(128) NOT NULL,
    action VARCHAR(16) NOT NULL,
    before_json VARCHAR(1024),                   -- 变更前快照（JSON）
    after_json VARCHAR(1024),                    -- 变更后快照（手工 JSON 拼接，避免引依赖）
    operator VARCHAR(64) NOT NULL,
    op_time TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sensitive_word_log_word ON t_sensitive_word_op_log (word_id);
CREATE INDEX IF NOT EXISTS idx_sensitive_word_log_time ON t_sensitive_word_op_log (op_time);

-- 敏感词命中痕迹（操作痕迹）：拦截/打码每一次命中逐词逐字段留痕，可定位到账号、字段、字位
-- 注意：BLOCK 场景业务事务回滚，本行由独立事务先落库（REQUIRES_NEW），保证“出状况能定位到人”
CREATE TABLE IF NOT EXISTS t_sensitive_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no VARCHAR(64),                      -- 业务请求号（可空：纯任务调用）
    username VARCHAR(64) NOT NULL,               -- 实际写入人
    module VARCHAR(32) NOT NULL,                 -- PROPERTY / LEASE / CHECKOUT / HANDOVER
    biz_ref VARCHAR(128),                        -- 业务定位：合同号/房源编号/交接班 id 等
    field_path VARCHAR(64) NOT NULL,             -- 字段定位：如 address.community / remark / content
    word_text VARCHAR(128) NOT NULL,             -- 命中的归一化词条
    category VARCHAR(32),
    action_taken VARCHAR(16) NOT NULL,           -- BLOCK / MASK
    raw_excerpt VARCHAR(255),                    -- 原文片段（截断存储，方便回看；不存全文）
    start_index INT NOT NULL,                    -- 命中起始字位（0 基，基于原文）
    end_index INT NOT NULL,                      -- 命中结束字位（排他，基于原文；含被剥离的插空字符）
    masked_text VARCHAR(255),                    -- MASK 后的字段全文（截断）；BLOCK 为空
    source_id BIGINT,                            -- 交接班等源记录 id
    request_time TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sensitive_audit_user_time ON t_sensitive_audit (username, request_time);
CREATE INDEX IF NOT EXISTS idx_sensitive_audit_biz ON t_sensitive_audit (module, biz_ref);
CREATE INDEX IF NOT EXISTS idx_sensitive_audit_word ON t_sensitive_audit (word_text);

