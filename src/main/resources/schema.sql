-- 房源台账：只增不改，更正通过 REVERSE 冲销单完成
CREATE TABLE IF NOT EXISTS t_property_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    property_code VARCHAR(64) NOT NULL,
    community VARCHAR(128),
    building VARCHAR(64),
    room_no VARCHAR(64),
    area DECIMAL(10,2),
    entry_type VARCHAR(16) NOT NULL,            -- REGISTER / REVERSE
    ref_entry_id BIGINT,                        -- 冲销单指向的原台账 id
    remark VARCHAR(512),
    request_no VARCHAR(64) NOT NULL,
    operator VARCHAR(64) NOT NULL,
    biz_time TIMESTAMP NOT NULL,
    data_version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_property_ledger_code ON t_property_ledger (property_code);
