-- ============================================================
-- apt-7 出租率额度预占模型（租约管理检查项）
--
-- 背景：出租率有额度控制，申请建档直接扣额度，并发下容易超扣。
-- 模型：申请先“预占”额度（HOLD），确认才“实扣”（CONFIRM），
--       取消或申请后 20 分钟未确认由后台扫描自动释放（RELEASE_CANCEL/RELEASE_TIMEOUT）。
-- 不变量：t_quota_balance.reserved 恒等于该小区 HELD 预占单 reserved_amount 之和；
--         余量 available = total - occupied - reserved 恒可查；
--         每次变化（预占/确认/取消释放/超时释放/配额调整）落一条 t_quota_journal，
--         余额变化全程可查、可对账。配额按小区维度（t_quota_balance，与数据范围口径一致）。
-- ============================================================

-- 小区出租率额度账（一个小区一行；由配额调整维护，留痕，不物理删除）
CREATE TABLE IF NOT EXISTS t_quota_balance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community VARCHAR(128) NOT NULL,              -- 小区（与台账 community、SCOPE 授权口径一致）
    total_amount INT NOT NULL,                   -- 配额：允许出租的上限（间/套）
    occupied_amount INT NOT NULL DEFAULT 0,      -- 已实扣：已确认占用的额度
    reserved_amount INT NOT NULL DEFAULT 0,      -- 预占中：HELD 预占单占用的额度（未确认）
    request_no VARCHAR(64),                      -- 最近一次写入的请求号
    operator VARCHAR(64) NOT NULL,
    biz_time TIMESTAMP NOT NULL,
    data_version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_quota_community UNIQUE (community)
);

-- 额度预占单：申请先占、确认实扣、取消/超时释放；状态单向流转，只增不删
CREATE TABLE IF NOT EXISTS t_quota_hold (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_no VARCHAR(64) NOT NULL,                -- 对外预占单号 HOLD-xxxx
    community VARCHAR(128) NOT NULL,             -- 预占额度所属小区
    biz_ref VARCHAR(128) NOT NULL,               -- 业务幂等键（同单不可重复预占）：本期=租约合同号
    reserve_amount INT NOT NULL,                 -- 预占额度（申请时先占余量，恒为 1）
    status VARCHAR(16) NOT NULL DEFAULT 'HELD',  -- HELD 预占中 / CONFIRMED 已实扣 / RELEASED 已释放
    release_reason VARCHAR(24),                  -- 释放原因：CANCEL 主动取消 / TIMEOUT 20分钟超时
    expires_at TIMESTAMP NOT NULL,               -- 预占到期时间（申请时间 + 20 分钟）
    confirmed_at TIMESTAMP,
    released_at TIMESTAMP,
-- 同单不可重复预占：active_biz_ref 为生成列——仅活跃单（HELD/CONFIRMED）取 biz_ref，
-- 释放后为 NULL；唯一索引允许多个 NULL，故“释放后可就同一合同重新申请”，
-- 而同一合同同时只可能存在一笔活跃预占单（并发插入由该唯一索引兜底，只成功一笔）。
    active_biz_ref VARCHAR(128) GENERATED ALWAYS AS
        (CASE WHEN status IN ('HELD','CONFIRMED') THEN biz_ref ELSE NULL END),
    request_no VARCHAR(64) NOT NULL,
    operator VARCHAR(64) NOT NULL,               -- 申请人（SELF 范围按本人过滤）
    biz_time TIMESTAMP NOT NULL,
    data_version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_quota_hold_no UNIQUE (hold_no)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_quota_hold_active_biz ON t_quota_hold (active_biz_ref);
CREATE INDEX IF NOT EXISTS idx_quota_hold_status_expire
    ON t_quota_hold (status, expires_at);
CREATE INDEX IF NOT EXISTS idx_quota_hold_community ON t_quota_hold (community);
CREATE INDEX IF NOT EXISTS idx_quota_hold_operator ON t_quota_hold (operator);

-- 额度流水账：每一次余额/配额变化一条，只增不改，余量变化全程可查、可对账
-- change_type: RESERVE 预占 / CONFIRM 确认实扣 / RELEASE_CANCEL 取消释放 /
--              RELEASE_TIMEOUT 超时释放 / ADJUST 配额调整
CREATE TABLE IF NOT EXISTS t_quota_journal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    community VARCHAR(128) NOT NULL,
    change_type VARCHAR(24) NOT NULL,
    hold_id BIGINT,                              -- 关联预占单（ADJUST 为空）
