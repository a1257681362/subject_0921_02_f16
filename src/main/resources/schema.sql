-- ============================================================
-- apt-10 房源归属树闭包表（管家对账用的房源归属结构）
--
-- 背景：管家自己记了本流水账，对账全靠房源归属树。归属关系原来隐式在台账文本里，
--       子树/祖先/同级只能现场拼。本期把归属树改成闭包表（Closure Table）模型：
-- 1. t_property_node：节点表（小区/楼栋/层/房间等层级节点），parent_id 记直接父，
--    sort_order 记同级顺序（同级排序走表结构，不靠内存），community 冗余到每个节点
--    供 apt-3 数据范围 SCOPE 按小区过滤。
-- 2. t_property_closure：闭包表，每个节点与其每一祖先之间一行（含自身 distance=0）。
--    子树查询 = ancestor_id 等值；祖先链 = descendant_id 等值按 distance 倒序；
--    换父用标准“删旧路径 × 接新路径”两条集合语句完成，子孙边自动跟随，无需递归重建。
-- 3. 环状引用直接拒绝：换父前先查“新父是否为本节点子孙（含自身）”，命中即拒绝；
--    结构上不可能产生环（挂到子孙下被拒绝，验收必查）。
-- ============================================================

-- 归属树节点：parent_id 记直接父（根为 NULL），sort_order 记同级次序
CREATE TABLE IF NOT EXISTS t_property_node (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_code VARCHAR(64) NOT NULL,               -- 节点业务编号（唯一）
    node_name VARCHAR(128) NOT NULL,              -- 节点名称（小区/楼栋/层/房间名）
    node_type VARCHAR(16),                        -- COMMUNITY / BUILDING / FLOOR / ROOM 等
    community VARCHAR(128),                       -- 所属小区（冗余：根节点取值，换父时整子树跟随更新）
    parent_id BIGINT,                             -- 直接父节点；根为 NULL
    sort_order INT NOT NULL DEFAULT 0,            -- 同级排序（同父下升序）
    request_no VARCHAR(64) NOT NULL,
    operator VARCHAR(64) NOT NULL,
    biz_time TIMESTAMP NOT NULL,
    data_version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_property_node_code UNIQUE (node_code)
);
CREATE INDEX IF NOT EXISTS idx_property_node_parent ON t_property_node (parent_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_property_node_community ON t_property_node (community);

-- 闭包表：(ancestor, descendant) 每一对祖-后代一行；distance=0 为自身行
-- 主键天然防止重复路径；子树/祖先链均走本表索引，不做递归查询
CREATE TABLE IF NOT EXISTS t_property_closure (
    ancestor_id BIGINT NOT NULL,
    descendant_id BIGINT NOT NULL,
    distance INT NOT NULL,                        -- 代际距离：0=自身，1=直接父子，越大越远
    CONSTRAINT pk_property_closure PRIMARY KEY (ancestor_id, descendant_id)
);
CREATE INDEX IF NOT EXISTS idx_property_closure_desc ON t_property_closure (descendant_id);
CREATE INDEX IF NOT EXISTS idx_property_closure_anc ON t_property_closure (ancestor_id);

