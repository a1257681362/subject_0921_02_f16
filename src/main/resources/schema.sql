    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_no VARCHAR(64) NOT NULL,
    property_code VARCHAR(64) NOT NULL,
    tenant_name VARCHAR(64) NOT NULL,
    tenant_phone VARCHAR(32),
    tenant_id_card VARCHAR(32),
    lease_start DATE NOT NULL,
    lease_end DATE NOT NULL,
    monthly_rent DECIMAL(12,2) NOT NULL,
    deposit DECIMAL(12,2) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',   -- ACTIVE / CLOSED
    request_no VARCHAR(64) NOT NULL,
    operator VARCHAR(64) NOT NULL,
    biz_time TIMESTAMP NOT NULL,
    data_version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_lease_contract_no UNIQUE (contract_no)
);
CREATE INDEX IF NOT EXISTS idx_lease_start ON t_lease (lease_start);

-- 退租记录：登记验房结果；一个合同只退一次
CREATE TABLE IF NOT EXISTS t_lease_checkout (
