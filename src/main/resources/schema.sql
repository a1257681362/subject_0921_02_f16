    data_version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_checkout_contract UNIQUE (contract_no)
);

-- 押金扣除明细：逐条留痕
