-- ============================================================
-- apt-9 租约签署断点回调：电子签章平台签署完成主动通知 + 平台回调安全规矩
--
-- 背景：签约归档任务第 12 步「等待租客签署」原先只靠定时轮询平台，签署完成到任务继续
--       之间有最长一个轮询间隔的断点。本期平台在租客签署完成后回调 EVOPS，即时唤醒任务；
--       轮询保留为兜底（回调丢失时任务仍会推进，不改变成功路径）。
-- 安全规矩（管家要求“定进系统，不靠自觉”，缺任一即拒绝）：
--   1. 请求带 X-EV-Key/X-EV-Timestamp/X-EV-Nonce/X-EV-Signature，
--      服务端按与出站同一把密钥、同一种算法（HMAC-SHA256，签名串 METHOD\nPATH\n
--      timestamp\nnonce\nbodyMd5）验签；签名覆盖报文全部参数（含空值字段）。
--   2. 时间戳取服务端时钟比对，与当前相差超过 8 分钟（过早/过晚）拒绝，防截获重放。
--   3. 同一 nonce 在 15 分钟内只许出现一次：验签通过后抢占插入本表，唯一键冲突即重放拒绝；
--      多实例部署由数据库唯一约束兜底。到期记录由定时任务清理（只删过期，不影响在窗判定）。
-- ============================================================

CREATE TABLE IF NOT EXISTS t_esign_nonce (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nonce VARCHAR(128) NOT NULL,                   -- 平台随机号（X-EV-Nonce）
    biz_no VARCHAR(128),                           -- 回调业务幂等号（EVOPS-合同号），便于排查重放来源
    request_timestamp BIGINT,                      -- 请求时间戳（毫秒，平台入参，已按服务端时钟校验通过）
    seen_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expire_at TIMESTAMP NOT NULL,                  -- 防重放窗口截止（seen_at + 15 分钟）
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_esign_nonce_nonce UNIQUE (nonce)
);
CREATE INDEX IF NOT EXISTS idx_esign_nonce_expire ON t_esign_nonce (expire_at);

