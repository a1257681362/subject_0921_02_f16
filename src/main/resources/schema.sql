-- ============================================================
-- apt-3 多角色权限并集：账号 / 角色 / 权限 / 数据范围 / 令牌 / 数据放行审计
-- 一个账号可兼多个角色：功能权限（菜单、按钮）取并集；
-- 数据范围 SELF < SCOPE < ALL 取最宽角色放行，并逐请求落审计。
-- 角色或账号停用后，授权每请求实时查库组装，立即收权（不等令牌过期）。
-- ============================================================

-- 账号
CREATE TABLE IF NOT EXISTS t_rbac_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    display_name VARCHAR(64),
    password_hash CHAR(64) NOT NULL,             -- SHA-256(password) 十六进制
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / DISABLED
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rbac_user_username UNIQUE (username)
);

-- 角色
CREATE TABLE IF NOT EXISTS t_rbac_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR(64) NOT NULL,
    role_name VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / DISABLED
    remark VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rbac_role_code UNIQUE (role_code)
);

-- 账号-角色（多对多）
CREATE TABLE IF NOT EXISTS t_rbac_user_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rbac_user_role UNIQUE (user_id, role_id)
);
CREATE INDEX IF NOT EXISTS idx_rbac_user_role_role ON t_rbac_user_role (role_id);

-- 权限点：MENU 菜单 / BUTTON 按钮（含查看、导出等动作级权限）
CREATE TABLE IF NOT EXISTS t_rbac_permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perm_code VARCHAR(128) NOT NULL,
    perm_name VARCHAR(128) NOT NULL,
    perm_type VARCHAR(16) NOT NULL,              -- MENU / BUTTON
    module VARCHAR(64) NOT NULL DEFAULT 'apartment',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rbac_perm_code UNIQUE (perm_code)
);

-- 角色-权限（多对多）
CREATE TABLE IF NOT EXISTS t_rbac_role_permission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rbac_role_permission UNIQUE (role_id, permission_id)
);
CREATE INDEX IF NOT EXISTS idx_rbac_role_perm_perm ON t_rbac_role_permission (permission_id);

-- 数据范围授权：可挂角色（subject_type=ROLE）或账号（subject_type=USER，用户级优先参与并集）
-- scope_level: SELF 仅本人经办 / SCOPE 指定片区（scope_value=小区名）/ ALL 全部
CREATE TABLE IF NOT EXISTS t_rbac_data_scope (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type VARCHAR(16) NOT NULL,          -- ROLE / USER
    subject_id BIGINT NOT NULL,
    scope_level VARCHAR(16) NOT NULL,           -- SELF / SCOPE / ALL
    scope_value VARCHAR(128),                   -- SCOPE 时为小区名，其余为空
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_rbac_data_scope_subject UNIQUE (subject_type, subject_id)
);

-- 登录令牌：不缓存授权，仅承载身份；停用/登出靠 revoked 与账号、角色状态实时判定
CREATE TABLE IF NOT EXISTS t_rbac_login_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(128) NOT NULL,
    user_id BIGINT NOT NULL,
    issued_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    last_seen_at TIMESTAMP,
    CONSTRAINT uk_rbac_login_token UNIQUE (token)
);
CREATE INDEX IF NOT EXISTS idx_rbac_token_user ON t_rbac_login_token (user_id);

-- 数据权限并集放行审计：每请求按最宽角色放行时留痕
CREATE TABLE IF NOT EXISTS t_data_scope_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no VARCHAR(64),                     -- 业务写接口的请求号；纯查询为空
    username VARCHAR(64) NOT NULL,
    user_roles VARCHAR(255) NOT NULL,           -- 当次生效的启用角色，逗号分隔
    widest_scope VARCHAR(16) NOT NULL,          -- 实际放行使用的最宽范围
    granted_by_role VARCHAR(64),                -- 提供最宽范围的角色编码（ALL/SCOPE 放行时必填）
    scope_value VARCHAR(128),                   -- SCOPE 时命中的小区
    resource VARCHAR(128) NOT NULL,             -- 放行的资源/接口
    query_params VARCHAR(1024),                 -- 查询条件摘要
    result_count INT,                           -- 本次返回行数
    request_time TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_data_scope_audit_user ON t_data_scope_audit (username, request_time);

