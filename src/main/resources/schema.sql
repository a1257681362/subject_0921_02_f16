-- ============================================================
-- apt-5 慢操作后台化：签约归档挪到后台任务
--
-- 1. 慢操作（签约 + 电子签章 + 归档）不再占用请求线程：接口只登记 t_async_task 立即返回，
--    后台调度器认领 PENDING 任务执行；前端按 taskNo 轮询进度（每一致步骤 5%，共 20 步）。
-- 2. 支持取消：cancel_requested 置位后，执行器在“下一个一致步骤”边界停下（当前步骤提交完），
--    任务落 CANCELLED，进度停在 5 的整数倍，可从此断点继续重跑。
-- 3. 失败可断点重跑：失败落 FAILED + fail_step/fail_reason，已完成步骤天然幂等，
--    重跑从 current_step+1 继续；实例宕机后启动时把 RUNNING 回收为 PENDING。
-- 4. 终态（SUCCESS/FAILED/CANCELLED）任务记录保留 14 天（retain_until），每日定时清理。
-- 5. 电子签章平台对接独立一层：默认内存 mock（下周演示零外部依赖），
--    provider=http 切真实网关（HMAC 签名、超时可控），任务步骤与接口不变。
-- ============================================================

-- 后台任务登记表：一种 task_type 对应一个步骤处理器（本期 SIGN_ARCHIVE）
CREATE TABLE IF NOT EXISTS t_async_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no VARCHAR(64) NOT NULL,                -- 对外任务编号（TASK-xxxx）
    task_type VARCHAR(32) NOT NULL,              -- SIGN_ARCHIVE 签约归档（预留其他慢操作）
    biz_ref VARCHAR(128),                        -- 业务定位：签约归档为合同号
    property_code VARCHAR(64),                   -- 房源编号：SCOPE 角色按授权片区过滤任务
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING', -- PENDING/RUNNING/SUCCESS/FAILED/CANCELLED
    progress INT NOT NULL DEFAULT 0,             -- 0-100，每个一致步骤 +5
    current_step INT NOT NULL DEFAULT 0,         -- 已提交完成的一致步骤序号（0-20）
    total_steps INT NOT NULL DEFAULT 20,
    fail_step INT,                               -- 失败发生在第几步（断点重跑起点 = current_step+1）
    fail_reason VARCHAR(1024),                   -- 失败原因（截断存储）
    cancel_requested BOOLEAN NOT NULL DEFAULT FALSE, -- 取消申请：执行器在下一步边界生效
    payload CLOB NOT NULL,                       -- 入参快照 JSON（断点重跑不依赖请求现场）
    checkpoint CLOB,                             -- 断点上下文 JSON（平台文书标识/租约 id/流水号等跨步骤产物）
    result_json VARCHAR(2048),                   -- 成功产物摘要（租约/归档/签章流水/文件）
    retry_count INT NOT NULL DEFAULT 0,
    request_no VARCHAR(64) NOT NULL,
    operator VARCHAR(64) NOT NULL,               -- 发起人（=登录账号；任务线程内以此落业务审计字段）
    locked_by VARCHAR(128),                      -- 执行节点/线程标识
    lock_at TIMESTAMP,
    next_run_at TIMESTAMP,                       -- 等待外部条件（如租客签署）时延后重领时间
    started_at TIMESTAMP,
    finished_at TIMESTAMP,
    retain_until TIMESTAMP,                      -- 终态记录保留截止时间（默认终态 +14 天）
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_async_task_no UNIQUE (task_no)
);
CREATE INDEX IF NOT EXISTS idx_async_task_status ON t_async_task (status);
CREATE INDEX IF NOT EXISTS idx_async_task_type_status ON t_async_task (task_type, status);
CREATE INDEX IF NOT EXISTS idx_async_task_operator ON t_async_task (operator);
CREATE INDEX IF NOT EXISTS idx_async_task_property ON t_async_task (property_code);
CREATE INDEX IF NOT EXISTS idx_async_task_biz ON t_async_task (task_type, biz_ref);
CREATE INDEX IF NOT EXISTS idx_async_task_retain ON t_async_task (retain_until);

