    delta_total INT NOT NULL DEFAULT 0,          -- 配额变化（仅 ADJUST 非 0）
    delta_occupied INT NOT NULL DEFAULT 0,       -- 已实扣变化（CONFIRM +1）
    delta_reserved INT NOT NULL DEFAULT 0,       -- 预占中变化（RESERVE +1 / CONFIRM -1 / RELEASE -1）
    total_after INT NOT NULL,                    -- 变化后配额
    occupied_after INT NOT NULL,                 -- 变化后已实扣
    reserved_after INT NOT NULL,                 -- 变化后预占中
    request_no VARCHAR(64),
    operator VARCHAR(64) NOT NULL,
    biz_time TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_quota_journal_community_time
    ON t_quota_journal (community, id);
CREATE INDEX IF NOT EXISTS idx_quota_journal_hold ON t_quota_journal (hold_id);
CREATE INDEX IF NOT EXISTS idx_quota_journal_biz ON t_quota_journal (biz_ref);

